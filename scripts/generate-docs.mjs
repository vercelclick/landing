import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(
  await readFile(path.join(rootDir, "content/docs-manifest.json"), "utf8"),
);
const docs = {};

for (const { categoryPath, filename, slug } of manifest) {
  const filePath = path.join(rootDir, "content/docs", categoryPath, filename);
  docs[slug] = await readFile(filePath, "utf8");
}

const output = `// Generated by scripts/generate-docs.mjs. Do not edit by hand.\nexport const docsContent: Record<string, string> = ${JSON.stringify(docs, null, 2)};\n`;

await writeFile(path.join(rootDir, "src/lib/generated-docs.ts"), output);
